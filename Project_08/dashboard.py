"""Read-only Streamlit dashboard displaying saved historical simulation results."""
import json
from pathlib import Path
import pandas as pd
import plotly.graph_objects as go
import streamlit as st
from plotly.subplots import make_subplots

st.set_page_config(page_title="BTC Event-Driven Backtesting", page_icon="📊", layout="wide")
st.title("BTC Event-Driven Backtesting Lab")
st.caption("Project 8 · Delta BTCUSD educational simulator · Historical data only · No broker connection")

folder = st.sidebar.text_input("Results directory", "demo_results")
tf = st.sidebar.selectbox("Timeframe", ["1m", "5m", "15m", "1h", "4h"], index=1)
base = Path(folder)/"BTCUSD"/tf

@st.cache_data(ttl=15, show_spinner=False)
def read_result(path, mtime):
    return json.loads(Path(path).read_text(encoding="utf-8"))

def load(section):
    p = base/f"{section}.json"
    if not p.is_file():
        st.warning(f"Missing {p}. Run: python main.py run --timeframes {tf} --output {folder}")
        st.stop()
    return read_result(str(p), p.stat().st_mtime_ns)

summary = load("summary")
equity = pd.DataFrame(load("equity"))
trades = pd.DataFrame(load("trades"))
orders = pd.DataFrame(load("orders"))
fills = pd.DataFrame(load("fills"))
events = pd.DataFrame(load("events"))
candles = pd.DataFrame(load("candles"))

st.info("The backtest is an USD-equivalent educational simulation. Delta India uses INR margin/settlement. Funding, mark-price liquidations, and detailed limit-order execution are not modeled.")
a,b,c,d,e = st.columns(5)
a.metric("Ending equity (USD)", f"${summary['ending_equity_usd']:,.2f}")
b.metric("Net return", f"{summary['return_pct']:+.2f}%")
c.metric("Max drawdown", f"{summary['max_drawdown_pct']:.2f}%")
d.metric("Order fills", summary['fill_count'])
e.metric("Trading fees + GST", f"${summary['total_fees_incl_gst_usd']:.2f}")

tab1,tab2,tab3,tab4,tab5 = st.tabs(["📈 Performance", "🕯️ Candles & Fills", "📋 Orders & Trades", "🔁 Event Timeline", "⚙️ Assumptions & Learning"])
with tab1:
    equity["time_utc"] = pd.to_datetime(equity["time_utc"], utc=True)
    fig = make_subplots(rows=2, cols=1, shared_xaxes=True, row_heights=[0.72,0.28], vertical_spacing=0.05)
    fig.add_trace(go.Scatter(x=equity.time_utc, y=equity.equity_usd, name="Equity (USD)", mode="lines"), row=1,col=1)
    fig.add_trace(go.Scatter(x=equity.time_utc, y=equity.drawdown_pct, name="Drawdown %", mode="lines",fill="tozeroy"),row=2,col=1)
    fig.update_layout(height=590, title="Equity & drawdown", xaxis_rangeslider_visible=False)
    st.plotly_chart(fig, use_container_width=True)
    st.dataframe(equity.tail(200).iloc[::-1], use_container_width=True)
with tab2:
    c = candles.copy()
    c["timestamp_utc"] = pd.to_datetime(c["timestamp_utc"], utc=True)
    fig = go.Figure(data=[go.Candlestick(x=c.timestamp_utc, open=c.open, high=c.high, low=c.low, close=c.close, name="BTCUSD")])
    if not fills.empty:
        f = fills.copy()
        f["time_utc"] = pd.to_datetime(f["time_utc"], utc=True)
        for action, symbol, color in [("OPEN_LONG","triangle-up","#22c55e"),("OPEN_SHORT","triangle-down","#ef4444"),
                                      ("CLOSE_LONG","x","#f59e0b"),("CLOSE_SHORT","x","#3b82f6")]:
            group=f[f.action == action]
            if not group.empty:
                fig.add_trace(go.Scatter(x=group.time_utc, y=group.fill_price, mode="markers", name=action,
                                         marker={"size":12,"symbol":symbol,"color":color}))
    fig.update_layout(height=610, title="Historical candles and actual simulated fill times", xaxis_rangeslider_visible=False)
    st.plotly_chart(fig, use_container_width=True)
with tab3:
    for name, frame in [("Orders", orders), ("Fills", fills), ("Closed trade fills", trades)]:
        st.subheader(name)
        st.dataframe(frame, use_container_width=True)
        if not frame.empty:
            st.download_button(f"Download {name.lower()} JSON", frame.to_json(orient="records", indent=2),
                               file_name=f"BTCUSD_{tf}_{name.lower().replace(' ','_')}.json",key=name)
with tab4:
    st.write("Each record is generated by the historical event loop, not by a live broker.")
    types = sorted(events.type.unique().tolist()) if not events.empty else []
    selected = st.multiselect("Filter event types", types, default=types)
    visible = events[events.type.isin(selected)] if selected else events.iloc[:0]
    st.dataframe(visible.tail(1000), use_container_width=True, height=470)
    if not events.empty:
        st.download_button("Download full event log", events.to_json(orient="records", indent=2), file_name=f"BTCUSD_{tf}_events.json")
with tab5:
    st.json(summary["assumptions"])
    st.markdown("""**Event order for every bar:**

1. **MARKET_OPEN** — the next bar starts, and queued orders may fill at its open.
2. **FILL / ORDER_REJECT** — validate size and update cash, open position, and fees.
3. **MARKET_CLOSE** — mark the position to the completed candle close.
4. **SIGNAL** — process Project 4's BUY/SELL/HOLD value only after close.
5. **ORDER** — queue an entry/exit market order for the **next contiguous candle open**.

**Gaps:** pending orders are cancelled rather than filled using unseen market intervals. No automatic flattening of existing positions. **End of data:** pending orders remain unfilled; open positions remain marked-to-market.

**Limitation:** this starter simulator does not model liquidation, funding, stop-loss orders, intra-candle orders, real liquidity, portfolio cross-margin, USD/INR FX, or real exchange fills.""")
    st.json(summary)
